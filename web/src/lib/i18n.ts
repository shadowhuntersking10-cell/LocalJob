export function translate(key: string, lang: Lang, vars?: Record<string, string | number>): string {
  const entry = dict[key]
  let value = entry ? entry[lang] || entry.en : key
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replace(new RegExp(`\\{${name}\\}`, 'g'), String(replacement))
    }
  }
  return value
}

export function translationCount() {
  return Object.keys(dict).length
}

export const SERVICE_VALUES = ['uz', 'en', 'ru'] as const

export function pickLang(value?: string | null): Lang {
  const candidate = (value || '').slice(0, 2).toLowerCase()
  return (SERVICE_VALUES as readonly string[]).includes(candidate) ? (candidate as Lang) : 'uz'
}
